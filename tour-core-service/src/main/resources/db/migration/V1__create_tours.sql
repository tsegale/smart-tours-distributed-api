-- Tour inventory. Owned by tour-core-service; no other service reads this database.
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE tours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200)          NOT NULL,
    description TEXT,
    price       NUMERIC(10, 2)        NOT NULL CHECK (price >= 0),
    currency    VARCHAR(3)            NOT NULL DEFAULT 'NAD',
    location    geometry(Point, 4326) NOT NULL,
    created_at  TIMESTAMPTZ           NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ           NOT NULL DEFAULT now(),
    version     BIGINT                NOT NULL DEFAULT 0
);

-- Radius search casts to geography (metres on the spheroid), so the index is on that same
-- expression. Without it, ST_DWithin does a sequential scan of every tour.
CREATE INDEX idx_tours_location_geog ON tours USING GIST (CAST(location AS geography));
